/* Makes src/omr/digits.js: time-signature and tuplet digits in common bold text fonts (the kind Finale,
   Sibelius and older engraving software print), for reading what the SMuFL examples in templates.js miss.

     python3 scripts/omr/digit-pages.py /tmp/omr/digits
     node scripts/omr/train-digits.mjs /tmp/omr/digits

   Each page goes through the same steps as in the app (src/omr/prepare.js, staff lines taken out) and every
   digit's ink in its box is kept as an example, in the same packed form as templates.js. */
import fs from 'fs';
import path from 'path';
import { prepare } from '../../src/omr/prepare.js';
import { features, shapeDist } from '../../src/omr/shapes.js';
import { pack } from '../../src/omr/classify.js';

const dir = process.argv[2];
function readP(f) {
  const b = fs.readFileSync(f); let p = 0;
  const tok = () => { while (/\s/.test(String.fromCharCode(b[p]))) p++; let s = ''; while (!/\s/.test(String.fromCharCode(b[p]))) s += String.fromCharCode(b[p++]); return s; };
  tok(); const w = +tok(), h = +tok(); tok(); p++;
  return { w, h, d: new Uint8Array(b.subarray(p, p + w * h)) };
}
const out = { time: [], tuplet: [] };
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.pgm')).sort()) {
  const base = path.join(dir, f.replace('.pgm', ''));
  const meta = JSON.parse(fs.readFileSync(base + '.json', 'utf8'));
  const p = prepare(readP(base + '.pgm'), { rotate: false });
  const { w, h } = p.R, sp = p.metrics.space, k = p.scale;
  const labels = new Int32Array(w * h);
  meta.items.forEach((it, n) => {
    const id = n + 1;
    let x0 = Infinity, x1 = -1, y0 = Infinity, y1 = -1;
    for (let y = Math.max(0, Math.floor(it.y0 * k) - 1); y <= Math.min(h - 1, Math.ceil(it.y1 * k) + 1); y++)
      for (let x = Math.max(0, Math.floor(it.x0 * k) - 1); x <= Math.min(w - 1, Math.ceil(it.x1 * k) + 1); x++)
        if (p.R.d[y * w + x]) { labels[y * w + x] = id; x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
    if (x1 < 0) return;
    out[it.kind].push({ cls: 't' + it.d, f: features(labels, w, { x0, x1, y0, y1, id }, sp) });
  });
}
/* a spread of examples per digit: farthest-point sampling */
function spread(list, per) {
  const by = new Map();
  list.forEach(e => { if (!by.has(e.cls)) by.set(e.cls, []); by.get(e.cls).push(e); });
  const keep = [];
  [...by.keys()].sort().forEach(cls => {
    const all = by.get(cls), chosen = [all[0]];
    const near = all.map(e => shapeDist(e.f, all[0].f));
    while (chosen.length < Math.min(per, all.length)) {
      let bi = 0; near.forEach((d, i) => { if (d > near[bi]) bi = i; });
      chosen.push(all[bi]);
      all.forEach((e, i) => { near[i] = Math.min(near[i], shapeDist(e.f, all[bi].f)); });
    }
    keep.push(...chosen);
  });
  return keep.map(e => pack(e.cls, e.f));
}
out.time = spread(out.time, 24); out.tuplet = spread(out.tuplet, 16);
const b64 = list => Buffer.from(Buffer.concat(list.map(a => Buffer.from(a)))).toString('base64');
fs.writeFileSync('src/omr/digits.js', `/* Generated by scripts/omr/train-digits.mjs from digits drawn in common bold text fonts (Liberation, DejaVu,
   FreeFont, Caladea): time signatures and tuplet numbers as Finale, Sibelius and older engraving software print
   them. Same records as templates.js. */
export const TIME_DATA = '${b64(out.time)}';
export const TUPLET_DATA = '${b64(out.tuplet)}';
`);
