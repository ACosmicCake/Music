/* Builds public/samples/ and src/content/samples.js from the recipes in recipes.mjs.

   Get the sources first (shallow clones are enough), then point the script at them:
     git clone --depth 1 https://github.com/sfzinstruments/dsmolken.double-bass /tmp/smolken
     GIT_LFS_SKIP_SMUDGE=1 git clone --depth 1 https://github.com/sgossner/VCSL /tmp/vcsl
     node scripts/samples/build.mjs --source smolken=/tmp/smolken --source vcsl=/tmp/vcsl [--only piano]

   Each note becomes a mono 44.1 kHz MP3: leading silence removed, cut to the recipe's length with a
   fade-out. Needs ffmpeg with libmp3lame. */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, statSync, writeFileSync, readdirSync, unlinkSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SOURCES, INSTRUMENTS } from './recipes.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'public', 'samples');
const args = process.argv.slice(2), srcDirs = {}, only = new Set();
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--source') { const [k, v] = args[++i].split('='); srcDirs[k] = v; }
  else if (args[i] === '--only') only.add(args[++i]);
}

const fileName = f => `${f.midi}-${f.layer}-${f.rr}.mp3`;
for (const inst of INSTRUMENTS) {
  if (only.size && !only.has(inst.id)) continue;
  const dir = srcDirs[inst.source];
  if (!dir) { console.log(`skip ${inst.id}: no --source ${inst.source}=…`); continue; }
  const outDir = join(OUT, inst.id);
  mkdirSync(outDir, { recursive: true });
  readdirSync(outDir).filter(n => n.endsWith('.mp3')).forEach(n => unlinkSync(join(outDir, n)));
  for (const f of inst.files) {
    const src = join(dir, f.src);
    if (!existsSync(src)) throw new Error(`${inst.id}: missing ${src}`);
    const af = [
      'silenceremove=start_periods=1:start_threshold=-60dB:start_silence=0.002',
      `atrim=end=${inst.maxSec}`,
      `afade=t=out:st=${inst.maxSec - inst.fade}:d=${inst.fade}`
    ].join(',');
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', src, '-ac', '1', '-ar', '44100', '-af', af, '-map_metadata', '-1',
      '-c:a', 'libmp3lame', '-q:a', '4', join(outDir, fileName(f))]);
  }
  console.log(`${inst.id}: ${inst.files.length} files`);
}

/* The manifest the app loads from: every built instrument, with the size of each file */
const sets = {};
for (const inst of INSTRUMENTS) {
  const outDir = join(OUT, inst.id);
  if (!existsSync(outDir)) continue;
  const files = inst.files.map(f => { const p = join(outDir, fileName(f)); return existsSync(p) ? [fileName(f), f.midi, f.layer, f.rr, statSync(p).size] : null; }).filter(Boolean);
  if (!files.length) continue;
  const layers = Math.max(...files.map(f => f[2])) + 1;
  sets[inst.id] = { name: inst.name, source: inst.source, gain: inst.gain, release: inst.release, layers,
    layerGain: inst.layerGain || null, bytes: files.reduce((a, f) => a + f[4], 0), files };
}
const used = Object.fromEntries(Object.entries(SOURCES).filter(([k]) => Object.values(sets).some(s => s.source === k)));
writeFileSync(join(ROOT, 'src', 'content', 'samples.js'),
  '/* Sampled instruments: generated by scripts/samples/build.mjs from scripts/samples/recipes.mjs. Do not edit by hand.\n' +
  '   files: [name, MIDI note, velocity layer (0 = softest), round-robin, bytes]. Credits: public/samples/LICENSES.md */\n' +
  'export const SAMPLE_SOURCES = ' + JSON.stringify(used, null, 2) + ';\n\n' +
  'export const SAMPLE_SETS = {\n' + Object.entries(sets).map(([id, s]) => {
    const { files, ...meta } = s;
    return `  ${id}: Object.assign(${JSON.stringify(meta)}, {\n    files: [\n${files.map(f => '      ' + JSON.stringify(f)).join(',\n')}\n    ]\n  })`;
  }).join(',\n') + '\n};\n');
console.log('manifest:', Object.entries(sets).map(([id, s]) => `${id} ${(s.bytes / 1e6).toFixed(2)} MB`).join(', '));
